import {chromium} from 'playwright';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];const external=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
await page.goto(new URL('../dist/lavadero-vista-3d.html',import.meta.url).href);
try { await page.waitForFunction(()=>window.modelReady===true,{timeout:30000}); } catch(e) { console.log({errors,status:await page.locator('#status').innerText()}); await page.screenshot({path:new URL('../dist/viewer-error.png',import.meta.url).pathname}); await browser.close(); throw e; }
await page.screenshot({path:new URL('../dist/preview-perspective.png',import.meta.url).pathname});
await page.getByRole('button',{name:'Superior',exact:true}).click();
await page.screenshot({path:new URL('../dist/preview-top.png',import.meta.url).pathname});
await page.getByRole('button',{name:'Base',exact:true}).click();
await page.screenshot({path:new URL('../dist/preview-bottom.png',import.meta.url).pathname});
await page.getByRole('button',{name:'Perspectiva',exact:true}).click();
await page.getByRole('button',{name:'Ver malla',exact:true}).click();
await page.screenshot({path:new URL('../dist/preview-wireframe.png',import.meta.url).pathname});
await page.getByRole('button',{name:'Ver malla',exact:true}).click();
const downloadEvent=page.waitForEvent('download');
await page.getByRole('button',{name:'Descargar modelo .glb ↓',exact:true}).click();
const download=await downloadEvent;
const bytes=fs.readFileSync(await download.path());
const same=bytes.equals(fs.readFileSync(new URL('../dist/lavadero-piedra.glb',import.meta.url)));
await page.getByRole('button',{name:'Giro automático',exact:true}).click();
const rotating=await page.getByRole('button',{name:'Pausar giro',exact:true}).getAttribute('aria-pressed');
await page.getByRole('button',{name:'Pausar giro',exact:true}).click();
await page.getByRole('button',{name:'Medidas',exact:true}).click();
const dimensions=await page.locator('#dimension-note').isVisible();
await page.getByRole('button',{name:'Medidas',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:new URL('../dist/preview-mobile.png',import.meta.url).pathname,fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
const stats=await page.evaluate(()=>window.modelStats);
const report={loaded:true,threejsStats:stats,consoleErrors:errors,externalRequests:external,downloadMatchesGLB:same,autoRotateControl:rotating==='true',dimensionsControl:dimensions,mobileNoHorizontalOverflow:!overflow};
fs.writeFileSync(new URL('../dist/viewer-validation.json',import.meta.url),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();
if(errors.length||external.length||!same||overflow)process.exit(1);
